//Un Pokemon con HP, attacco, difesa, status (avvelenato, KO, paralizzato, addormentato)
public class Pokemon {
    private int hp;
    private int atk;
    private int difesa;
    private String status;

    public Pokemon(int hp, int atk, int difesa, String status) {
        this.hp = hp;
        this.atk = atk;
        this.difesa = difesa;
        this.status = status;
    }

    
}
